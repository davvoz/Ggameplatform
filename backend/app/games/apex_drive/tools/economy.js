/**
 * The career's rules as plain data, for the server (apex_drive_be), which
 * holds every career and checks every purchase and race against them. The
 * game's config stays the only place they are written: export-economy.js
 * writes this to the server's economy.json, and tests/economy.test.js fails
 * when that file is out of date.
 */
import { DRIVERS } from '../js/config/Drivers.js';
import { MODS } from '../js/config/Mods.js';
import { BASE_STATS, PARTS } from '../js/config/Parts.js';
import { PICKUP_LAYOUT, PICKUPS } from '../js/config/Pickups.js';
import { PHYSICS, PODIUM, PRIZES, START_CREDITS } from '../js/config/Tuning.js';
import { WORLDS } from '../js/config/Worlds.js';
import { layPickups } from '../js/sim/Pickups.js';
import { trackOf } from '../js/sim/setup.js';

/** Where the server reads it, from the game's folder. */
export const ECONOMY_FILE = new URL('../../apex_drive_be/economy.json', import.meta.url);

/** The cash a lap's pickups pay at most (before the car's cashBonus). */
function cashPerLap(track) {
    return layPickups(track, PICKUPS, PICKUP_LAYOUT).filter((item) => item.kind === 'cash').length * PICKUPS.cash.value;
}

export function economyData() {
    const trackIds = WORLDS.flatMap((world) => world.tracks);
    return {
        note: 'Generated by apex_drive/tools/export-economy.js from the game config: do not edit by hand.',
        startCredits: START_CREDITS,
        podium: PODIUM,
        prizes: PRIZES,
        racers: DRIVERS.length + 1,
        physics: { maxNitro: PHYSICS.maxNitro, refSpeed: PHYSICS.refSpeed },
        base: BASE_STATS,
        parts: Object.fromEntries(Object.entries(PARTS).map(([id, part]) => [id, part.tiers.map(({ price, effect }) => ({ price, effect }))])),
        mods: Object.fromEntries(Object.entries(MODS).map(([id, { price, energy, effect }]) => [id, { price, energy, effect }])),
        worlds: WORLDS.map(({ id, prizeScale, tracks }) => ({ id, prizeScale, tracks })),
        tracks: Object.fromEntries(trackIds.map((id) => {
            const track = trackOf(id);
            return [id, { name: track.name, laps: track.laps, lapLength: Math.round(track.length), cashPerLap: cashPerLap(track) }];
        })),
    };
}

export function economyJson() {
    return `${JSON.stringify(economyData(), null, 2)}\n`;
}
