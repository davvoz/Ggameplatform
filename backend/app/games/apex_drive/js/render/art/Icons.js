/** Every icon painted once, at 1x and 2x: icons[name][scale]. */
export function paintIcons() {
    return Object.fromEntries(Object.entries(ICONS).map(([name, rows]) => [
        name,
        { 1: paintRows(rows, INK, 1), 2: paintRows(rows, INK, 2) },
    ]));
}
